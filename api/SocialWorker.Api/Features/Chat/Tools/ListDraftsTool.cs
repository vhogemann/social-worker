using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using System.Threading.Tasks;
using SocialWorker.Api.Data;
using SocialWorker.Api.Features.Drafts;

namespace SocialWorker.Api.Features.Chat.Tools;

public sealed record ListDraftsArgs(
    Guid? WorkflowId = null,
    List<Guid>? WorkflowIds = null,
    bool? IsPublished = null,
    string? Status = null,
    string? Stage = null,
    DateTime? Since = null,
    int? Limit = null
);

public sealed record ListDraftsResultItem(
    Guid Id,
    string Title,
    string Status,
    string? TargetPlatform,
    Guid? AutomationWorkflowId,
    string? AutomationWorkflowTitle,
    bool IsPublished,
    List<string> PublishedUrls,
    DateTime CreatedAt,
    DateTime UpdatedAt
);

public sealed record ListDraftsResult(IReadOnlyList<ListDraftsResultItem> Items) : IChatToolResult, IReadOnlyList<ListDraftsResultItem>
{
    public int Count => Items.Count;

    public ListDraftsResultItem this[int index] => Items[index];

    public IEnumerator<ListDraftsResultItem> GetEnumerator() => Items.GetEnumerator();

    System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();

    public string ToDisplayText()
    {
        if (Items.Count == 0)
        {
            return "No drafts found matching the criteria.";
        }

        var lines = Items.Select(item =>
        {
            var pub = item.IsPublished ? $"[Published: {string.Join(", ", item.PublishedUrls)}]" : "[Unpublished]";
            var wf = !string.IsNullOrEmpty(item.AutomationWorkflowTitle) ? $" (Workflow: {item.AutomationWorkflowTitle})" : "";
            return $"- {item.Id}: \"{item.Title}\" ({item.Status}, Platform: {item.TargetPlatform ?? "Canonical"}) {pub}{wf}";
        });
        return string.Join("\n", lines);
    }
}

public sealed class ListDraftsTool : ChatToolBase<ListDraftsArgs, ListDraftsResult>
{
    private readonly DraftsService _draftsService;

    public ListDraftsTool(DraftsService draftsService)
    {
        _draftsService = draftsService;
    }

    public override string Name => "list_drafts";
    public override string Description => "List and filter user drafts by workflow ID, publication status, date range, or status.";

    public override JsonElement Parameters { get; } = JsonDocument.Parse("""
        {
          "type": "object",
          "properties": {
            "workflowId": { "type": "string", "description": "Optional UUID of a workflow to filter drafts generated by it." },
            "isPublished": { "type": "boolean", "description": "Filter by publication status (true = only published drafts with live posts)." },
            "status": { "type": "string", "description": "Filter by draft status (Editing, Formatting, Ready, Sent, Failed)." },
            "stage": { "type": "string", "description": "Filter by platform thread stage (Draft, Sourcing, Refining, Formatting, Ready, Sent)." },
            "since": { "type": "string", "description": "Filter drafts created/updated since an ISO-8601 timestamp (e.g. '2026-09-01T00:00:00Z')." },
            "limit": { "type": "integer", "description": "Maximum number of drafts to return (default: 20)." }
          },
          "required": []
        }
        """).RootElement.Clone();

    public override async Task<ListDraftsResult> ExecuteAsync(ListDraftsArgs args, Models.ToolExecutionContext context)
    {
        DraftStatus? statusEnum = null;
        if (!string.IsNullOrWhiteSpace(args.Status) && Enum.TryParse<DraftStatus>(args.Status, true, out var parsedStatus))
        {
            statusEnum = parsedStatus;
        }

        PlatformThreadStage? stageEnum = null;
        if (!string.IsNullOrWhiteSpace(args.Stage) && Enum.TryParse<PlatformThreadStage>(args.Stage, true, out var parsedStage))
        {
            stageEnum = parsedStage;
        }

        var filter = new DraftQueryFilter(
            WorkflowIds: args.WorkflowIds,
            WorkflowId: args.WorkflowId,
            Status: statusEnum,
            Stage: stageEnum,
            IsPublished: args.IsPublished,
            Since: args.Since,
            Limit: args.Limit ?? 20
        );

        var drafts = await _draftsService.GetDraftsForUserAsync(context.UserId, filter, context.CancellationToken);

        var items = drafts.Select(d =>
        {
            var isPub = false;
            var urls = new List<string>();

            if (d.Threads != null)
            {
                foreach (var t in d.Threads)
                {
                    if (t.Stage == "Sent") isPub = true;
                    if (t.Posts != null)
                    {
                        urls.AddRange(t.Posts.Where(p => !string.IsNullOrWhiteSpace(p.Url)).Select(p => p.Url!));
                    }
                }
            }

            if (d.Variants != null)
            {
                foreach (var v in d.Variants)
                {
                    if (v.Threads != null)
                    {
                        foreach (var vt in v.Threads)
                        {
                            if (vt.Stage == "Sent") isPub = true;
                            if (vt.Posts != null)
                            {
                                urls.AddRange(vt.Posts.Where(p => !string.IsNullOrWhiteSpace(p.Url)).Select(p => p.Url!));
                            }
                        }
                    }
                }
            }

            return new ListDraftsResultItem(
                d.Id,
                d.Title,
                d.Status,
                d.TargetPlatform,
                d.AutomationWorkflowId,
                d.AutomationWorkflowTitle,
                isPub,
                urls.Distinct().ToList(),
                d.CreatedAt,
                d.UpdatedAt
            );
        }).ToList();

        return new ListDraftsResult(items);
    }
}
